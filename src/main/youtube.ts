function normalizeQuery(value: string): string {
  return String(value || '').trim().replace(/\s+/g, ' ').slice(0, 200);
}

function normalizeText(value: string): string {
  return String(value || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}

interface VideoMetadata {
  videoId: string;
  title: string;
  author: string;
}

async function fetchVideoMetadata(videoId: string): Promise<VideoMetadata> {
  try {
    const response = await net.fetch(
      `https://www.youtube.com/oembed?url=${encodeURIComponent(`https://www.youtube.com/watch?v=${videoId}`)}&format=json`,
      { headers: { accept: 'application/json' } },
    );
    if (!response.ok) return { videoId, title: '', author: '' };
    const data = await response.json();
    return {
      videoId,
      title: String(data?.title || ''),
      author: String(data?.author_name || ''),
    };
  } catch {
    return { videoId, title: '', author: '' };
  }
}

